# 第3コマ データ集め、データ(変数)の尺度

import pandas as pd

# --- 例1: 尺度の違う変数が混ざった小さな表 ---
df = pd.DataFrame({
    "血液型": ["A", "B", "O", "A", "AB", "A"],        # 名義尺度
    "満足度": [5, 4, 3, 5, 4, 2],                      # 間隔尺度(感覚を数値化したもの)
    "気温": [21.5, 23.0, 19.5, 25.0, 27.5, 22.0],      # 間隔尺度
    "身長": [160, 172, 158, 180, 166, 171],            # 比尺度
})
print(df)

# --- 例2: 尺度に合った要約 ---
# 名義尺度: 数えられるのは人数(度数)だけ
print(df["血液型"].value_counts())
# 間隔尺度(感覚の数値化): 平均も使う。ただし倍率は言えない
print("満足度の平均:", df["満足度"].mean(), "/ 中央値:", df["満足度"].median())
# 間隔・比尺度: 平均が意味を持つ
print("気温の平均:", df["気温"].mean())
print("身長の平均:", df["身長"].mean())

# --- 例3: やってはいけない計算 ---
# 血液型に番号(A=1,B=2,O=3,AB=4)を振って平均しても、意味はありません。
# 「平均すると2.3型」という言葉が何も伝えないことを、言葉で確認しましょう。
# 背番号や郵便番号のような「数字符号」も同じで、名義尺度として扱います。

# --- 例4: 水準を取り出す ---
print("血液型の水準:", df["血液型"].unique())
print("満足度の水準:", sorted(df["満足度"].unique()))
# 満足度のような人の感覚を数値にしたものは、間隔尺度として扱います。
